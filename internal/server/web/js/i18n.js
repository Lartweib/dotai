const dicts = { en, es };

function stored() {
  try {
    return localStorage.getItem(langKey);
  } catch {
    return null;
  }
}

function initial() {
  const s = stored();
  if (s && dicts[s]) return s;
  return /^es\b/i.test(navigator.language || "") ? "es" : "en";
}

let current = initial();
document.documentElement.lang = current;

export const lang = () => current;
export const locale = () => (current === "es" ? "es" : "en");

// setLang switches the language, remembers it in this browser, and sets
// the lang of the page.
export function setLang(id) {
  if (!dicts[id]) return;
  current = id;
  document.documentElement.lang = id;
  try {
    localStorage.setItem(langKey, id);
  } catch {
    // The choice lasts for this visit only.
  }
}

// t gives the words of key in the chosen language, with {name} replaced
// by params.name. A value with plural forms picks one by params.n. A key
// the dictionaries lack gives fallback, or the key itself.
export function t(key, params = {}, fallback) {
  let v = dicts[current][key] ?? en[key];
  if (v === undefined) return fallback !== undefined ? fallback : key;
  if (typeof v === "object") {
    const form = new Intl.PluralRules(locale()).select(Number(params.n) || 0);
    v = v[form] ?? v.other;
  }
  return v.replace(/\{(\w+)\}/g, (m, k) => (params[k] !== undefined ? fmtParam(params[k]) : m));
}

// lower is a word in lower case, in the chosen language.
export const lower = (s) => String(s).toLocaleLowerCase(locale());

const fmtParam = (v) => (typeof v === "number" ? new Intl.NumberFormat(locale()).format(v) : String(v));

const valid = (iso) => {
  const d = iso instanceof Date ? iso : new Date(iso);
  return Number.isNaN(d.getTime()) || d.getFullYear() < 2000 ? null : d;
};

// fmtDate is a date and time in the viewer's zone and language.
export function fmtDate(iso) {
  const d = valid(iso);
  return d ? new Intl.DateTimeFormat(locale(), { dateStyle: "medium", timeStyle: "short" }).format(d) : "";
}

// fmtTime is the time of day of a date.
export function fmtTime(date) {
  const d = valid(date);
  return d ? new Intl.DateTimeFormat(locale(), { timeStyle: "short" }).format(d) : "";
}

// fmtRelative says how long ago a date was: "3 hours ago", "yesterday";
// past a month it gives the date itself.
export function fmtRelative(iso) {
  const d = valid(iso);
  if (!d) return "";
  const s = (d.getTime() - Date.now()) / 1000;
  const rtf = new Intl.RelativeTimeFormat(locale(), { numeric: "auto" });
  const a = Math.abs(s);
  if (a < 45) return rtf.format(0, "second");
  if (a < 3600) return rtf.format(Math.round(s / 60), "minute");
  if (a < 86400) return rtf.format(Math.round(s / 3600), "hour");
  if (a < 30 * 86400) return rtf.format(Math.round(s / 86400), "day");
  return new Intl.DateTimeFormat(locale(), { dateStyle: "medium" }).format(d);
}

// The codes the page gives itself, whose message is no word of dotai.
const local = new Set(["aborted", "network", "session", "no-session", "bad-response"]);

// errorText is an API error for people: the words of its code in the
// chosen language, and what the server said as its detail. An unknown
// code shows the server's message itself.
export function errorText(error) {
  const code = (error && error.code) || "unknown";
  const message = (error && error.message) || "";
  // An internal error has no words of its own: what dotai says is the news.
  const known = code === "internal" && message ? null : dicts[current]["errors." + code] ?? en["errors." + code];
  return {
    text: known || message || t("errors.unknown"),
    detail: message && known && !local.has(code) ? code + ": " + message : "",
    extra: error && error.maybeRan ? t("errors.maybeRan") : "",
  };
}
