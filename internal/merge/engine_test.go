package merge_test

import (
	"bytes"
	"encoding/json"
	"reflect"
	"testing"

	"github.com/lartweib/dotai/internal/merge"
)

// TestStagingAddEngine checks the engine layer of decision 0045, staged
// after the base and the variant: the profiling skill, and a sessionStart
// hook in each harness's block, appended to the block's own sessionStart,
// or after the shared sessionStart hooks copied into a block that has
// none, so that the pack's hooks still reach that harness.
func TestStagingAddEngine(t *testing.T) {
	engine := merge.Engine{
		Skill: []byte("skill\n"),
		Hooks: []merge.BlockHook{
			{Block: "claudecode", Entry: json.RawMessage(`{"matcher":"startup","command":"dotai c"}`)},
			{Block: "antigravity-cli", Entry: json.RawMessage(`{"command":"dotai g"}`)},
		},
	}
	tests := []struct {
		name    string
		layers  []src
		want    string
		origins map[string]string
	}{
		{
			name: "no hooks in the pack",
			want: `{"version":1,"hooks":{},"claudecode":{"hooks":{"sessionStart":[{"matcher":"startup","command":"dotai c"}]}},` +
				`"antigravity-cli":{"hooks":{"sessionStart":[{"command":"dotai g"}]}}}`,
			origins: map[string]string{"/version": "dotai", "/claudecode/hooks/sessionStart/0": "dotai", "/antigravity-cli/hooks/sessionStart/0": "dotai"},
		},
		{
			name:   "shared sessionStart hooks are copied into a new block first",
			layers: []src{hooks(`{"version": 1, "hooks": {"sessionStart": [{"command": "a"}], "stop": [{"command": "s"}]}}`)},
			want: `{"version":1,"hooks":{"sessionStart":[{"command":"a"}],"stop":[{"command":"s"}]},` +
				`"claudecode":{"hooks":{"sessionStart":[{"command":"a"},{"matcher":"startup","command":"dotai c"}]}},` +
				`"antigravity-cli":{"hooks":{"sessionStart":[{"command":"a"},{"command":"dotai g"}]}}}`,
			origins: map[string]string{"/version": "base", "/hooks/sessionStart/0": "base", "/hooks/stop/0": "base",
				"/claudecode/hooks/sessionStart/0": "base", "/claudecode/hooks/sessionStart/1": "dotai",
				"/antigravity-cli/hooks/sessionStart/0": "base", "/antigravity-cli/hooks/sessionStart/1": "dotai"},
		},
		{
			name: "a block's own sessionStart gets the entry appended",
			layers: []src{hooks(`{"hooks": {"sessionStart": [{"command": "a"}]}, "claudecode": {"hooks": {"stop": [{"command": "s"}]}},` +
				` "antigravity-cli": {"hooks": {"sessionStart": [{"command": "g"}]}}}`)},
			want: `{"hooks":{"sessionStart":[{"command":"a"}]},"claudecode":{"hooks":{"stop":[{"command":"s"}],"sessionStart":[{"command":"a"},{"matcher":"startup","command":"dotai c"}]}},` +
				`"antigravity-cli":{"hooks":{"sessionStart":[{"command":"g"},{"command":"dotai g"}]}}}`,
			origins: map[string]string{"/hooks/sessionStart/0": "base", "/claudecode/hooks/stop/0": "base",
				"/claudecode/hooks/sessionStart/0": "base", "/claudecode/hooks/sessionStart/1": "dotai",
				"/antigravity-cli/hooks/sessionStart/0": "base", "/antigravity-cli/hooks/sessionStart/1": "dotai"},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			s, diags := merge.Stage(newPack(base(tt.layers...)), merge.Selection{})
			if len(diags) > 0 {
				t.Fatalf("Stage() = %v", diags)
			}
			s.AddEngine(engine)
			skill := staged(t, s.User, ".rulesync/skills/dotai-profiles/SKILL.md")
			if string(skill.Data) != "skill\n" || skill.Layer != "" || skill.Generator != merge.GeneratorDotai {
				t.Errorf("skill = %+v, want the engine's, generated by dotai", skill)
			}
			h := staged(t, s.User, merge.HooksFile)
			if compact := compactJSON(t, h.Data); compact != tt.want {
				t.Errorf("hooks =\n%s\nwant\n%s", compact, tt.want)
			}
			if !reflect.DeepEqual(h.Origins, tt.origins) {
				t.Errorf("origins = %v, want %v", h.Origins, tt.origins)
			}
		})
	}
}

// TestStagingAddEngineOnlySkill checks an engine layer without hooks, as
// when no harness can run the hook: the pack's hooks stay as they are.
func TestStagingAddEngineOnlySkill(t *testing.T) {
	s, _ := merge.Stage(newPack(base()), merge.Selection{})
	s.AddEngine(merge.Engine{Skill: []byte("skill\n")})
	for _, f := range s.User {
		if f.Path == merge.HooksFile {
			t.Errorf("staged %s without hooks to add", f.Path)
		}
	}
	staged(t, s.User, ".rulesync/skills/dotai-profiles/SKILL.md")
}

func compactJSON(t *testing.T, data []byte) string {
	t.Helper()
	var b bytes.Buffer
	if err := json.Compact(&b, data); err != nil {
		t.Fatal(err)
	}
	return b.String()
}
